#!/usr/bin/env bash

set -euo pipefail

ROOT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
OUTPUT_DIR="$ROOT_DIR/win64_build"
WINDOWS_TEMPLATE="$ROOT_DIR/windows"
ARGOS_ROOT="$ROOT_DIR/data/argos-translate"

require_file() {
  if [[ ! -f "$1" ]]; then
    printf 'Required file is missing: %s\n' "$1" >&2
    exit 1
  fi
}

require_dir() {
  if [[ ! -d "$1" ]]; then
    printf 'Required directory is missing: %s\n' "$1" >&2
    exit 1
  fi
}

copy_file() {
  cp --reflink=auto -- "$1" "$2"
}

copy_tree() {
  cp -a --reflink=auto -- "$1" "$2"
}

require_dir "$WINDOWS_TEMPLATE"
require_file "$WINDOWS_TEMPLATE/build.ps1"
require_file "$WINDOWS_TEMPLATE/install-build-tools.ps1"
require_file "$WINDOWS_TEMPLATE/desktop.py"
require_file "$WINDOWS_TEMPLATE/package_progress.py"
require_file "$WINDOWS_TEMPLATE/runtime_audit.py"
require_file "$WINDOWS_TEMPLATE/requirements-desktop.txt"

for source_file in \
  dict.py \
  get_sounds.py \
  lookup_parse.py \
  requirements.txt \
  translate.py \
  dictionaries.db \
  SoundEn.lsa \
  1_star.txt \
  2_star.txt \
  3_star.txt \
  zen.txt \
  thinking-fast-and-slow.txt; do
  require_file "$ROOT_DIR/$source_file"
done

for source_dir in \
  docs \
  web \
  vendor; do
  require_dir "$ROOT_DIR/$source_dir"
done

require_dir "$ARGOS_ROOT/packages"

require_dir "$ROOT_DIR/dictapp"

require_dir "$ROOT_DIR/stubs/stanza"

require_file "$ROOT_DIR/docs/manual/README.md"
require_file "$ROOT_DIR/docs/manual/README.ru.md"

if [[ -e "$OUTPUT_DIR" || -L "$OUTPUT_DIR" ]]; then
  # Preserve dependency and compiler caches between preparations.
  rm -rf -- "$OUTPUT_DIR/backend" "$OUTPUT_DIR/resources" "$OUTPUT_DIR/seed_data" "$OUTPUT_DIR/tauri"
fi

mkdir -p \
  "$OUTPUT_DIR/backend" \
  "$OUTPUT_DIR/resources" \
  "$OUTPUT_DIR/seed_data/argos-translate/cache/argos-translate" \
  "$OUTPUT_DIR/seed_data/nltk_data/corpora"

copy_tree "$WINDOWS_TEMPLATE/." "$OUTPUT_DIR/"

for source_file in \
  dict.py \
  get_sounds.py \
  lookup_parse.py \
  requirements.txt \
  translate.py; do
  copy_file "$ROOT_DIR/$source_file" "$OUTPUT_DIR/backend/$source_file"
done

copy_tree "$ROOT_DIR/dictapp" "$OUTPUT_DIR/backend/"
copy_tree "$ROOT_DIR/stubs" "$OUTPUT_DIR/backend/"

for source_file in \
  example.jpg \
  dictionaries.db \
  SoundEn.lsa \
  1_star.txt \
  2_star.txt \
  3_star.txt \
  zen.txt \
  thinking-fast-and-slow.txt; do
  copy_file "$ROOT_DIR/$source_file" "$OUTPUT_DIR/resources/$source_file"
done

# Word lookups are served from the prebuilt dictionaries.db (copied above); the
# source StarDict files are only needed at build time to generate it, so they
# are not staged into the distribution.
for source_dir in \
  docs \
  web \
  vendor; do
  copy_tree "$ROOT_DIR/$source_dir" "$OUTPUT_DIR/resources/"
done

copy_tree \
  "$ARGOS_ROOT/packages" \
  "$OUTPUT_DIR/seed_data/argos-translate/"

if [[ -d "$ARGOS_ROOT/cache/argos-translate/spacy" ]]; then
  copy_tree \
    "$ARGOS_ROOT/cache/argos-translate/spacy" \
    "$OUTPUT_DIR/seed_data/argos-translate/cache/argos-translate/"
fi

WORDNET_ARCHIVE=""
for candidate in \
  "$ROOT_DIR/data/nltk_data/corpora/wordnet.zip" \
  "$HOME/nltk_data/corpora/wordnet.zip" \
  "$ROOT_DIR/.venv/share/nltk_data/corpora/wordnet.zip"; do
  if [[ -f "$candidate" ]]; then
    WORDNET_ARCHIVE="$candidate"
    break
  fi
done

if [[ -n "$WORDNET_ARCHIVE" ]]; then
  copy_file \
    "$WORDNET_ARCHIVE" \
    "$OUTPUT_DIR/seed_data/nltk_data/corpora/wordnet.zip"
elif [[ -x "$ROOT_DIR/.venv/bin/python" ]]; then
  "$ROOT_DIR/.venv/bin/python" -m nltk.downloader \
    -d "$OUTPUT_DIR/seed_data/nltk_data" \
    wordnet
else
  printf '%s\n' \
    'WordNet is missing and .venv/bin/python is unavailable.' \
    'Install the project environment or place wordnet.zip under:' \
    '  data/nltk_data/corpora/wordnet.zip' >&2
  exit 1
fi


cat >"$OUTPUT_DIR/GENERATED.txt" <<'EOF'
This directory is generated by prepare_win64_build.sh.
Do not edit or commit files here; edit the root sources or windows/ template.
EOF

printf 'Generated %s\n' "$OUTPUT_DIR"
du -sh "$OUTPUT_DIR"
